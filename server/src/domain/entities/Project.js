export default class Project {
  constructor({
    id,
    slug,
    title,
    category = null,
    summary = null,
    description = null,
    challenge = null,
    solution = null,
    role = null,
    duration = null,
    year = null,
    tech = [],
    results = [],
    githubUrl = null,
    liveUrl = null,
    imageUrl = null,
    color = null,
    featured = false,
    sortOrder = 0,
    createdAt = null,
  }) {
    Object.assign(this, {
      id,
      slug,
      title,
      category,
      summary,
      description,
      challenge,
      solution,
      role,
      duration,
      year,
      tech: tech || [],
      results: results || [],
      githubUrl,
      liveUrl,
      imageUrl,
      color,
      featured: Boolean(featured),
      sortOrder: sortOrder ?? 0,
      createdAt,
    });
  }
}
